#!/bin/bash
# Set up the browser extension that feeds captions to ReadSubtitles.
#
# Generates a shared token, writes it where both the extension and the app can
# read it, and prints the one manual step that cannot be scripted: loading an
# unpacked extension, which Chrome deliberately requires a human to do.
#
# Safe to re-run. It keeps the existing token so an already-installed extension
# keeps working.
set -euo pipefail

cd "$(dirname "$0")/.."

SUPPORT="$HOME/Library/Application Support/readsubtitles"
TOKEN_FILE="$SUPPORT/bridge-token"
PORT="${READSUBTITLES_PORT:-53117}"

mkdir -p "$SUPPORT"

if [ -s "$TOKEN_FILE" ]; then
  TOKEN="$(cat "$TOKEN_FILE")"
  echo "reusing the existing token"
else
  # openssl rather than a tr/head pipe: head closing the pipe sends tr a
  # SIGPIPE, which `set -o pipefail` turns into a silent early exit.
  TOKEN="$(openssl rand -hex 20)"
  printf '%s' "$TOKEN" > "$TOKEN_FILE"
  # The token is the only thing stopping any page you visit from making the app
  # speak, so it is not readable by other users on the machine.
  chmod 600 "$TOKEN_FILE"
  echo "generated a new token"
fi

cat > extension/config.js <<CONFIG
// Generated by bundle/make-extension.sh. Do not edit or commit.
const CONFIG = {
  port: $PORT,
  token: "$TOKEN",
};
CONFIG

echo
echo "Extension configured for port $PORT."
echo
echo "Load it once, by hand (Chrome requires a human for unpacked extensions):"
echo
echo "  1. Open  chrome://extensions  in the browser you watch in"
echo "  2. Turn on 'Developer mode' (top right)"
echo "  3. Click 'Load unpacked'"
echo "  4. Choose:  $(pwd)/extension"
echo
echo "Then switch the app to the browser source:"
echo
echo "  readsubtitles --source browser --save"
echo
echo "or pick 'Captions from browser' in the menu bar under Source."
